#!/usr/bin/env node

import fs from 'node:fs/promises'
import path from 'node:path'

const API_BASE = 'https://oldschoolessentials.necroticgnome.com/srd/api.php'
const PAGE_BASE = 'https://oldschoolessentials.necroticgnome.com/srd/index.php'
const INDEX_PAGE = 'Monster_Descriptions'
const OUTPUT_DEFAULT = 'src/features/monsters/generatedOseRawMonsters.ts'

function usage() {
  console.error(
    'Usage: node scripts/fetch-ose-monsters-raw.mjs [output-path]\n' +
      `Example: node scripts/fetch-ose-monsters-raw.mjs ${OUTPUT_DEFAULT}`,
  )
}

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      'user-agent': 'HomeBoysHouse OSE monster importer',
      accept: 'application/json',
    },
  })
  if (!response.ok) {
    throw new Error(`Request failed: ${response.status} ${response.statusText} for ${url}`)
  }
  return response.json()
}

function decodeHtml(text) {
  return text
    .replace(/&#039;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
}

function normalizeLine(text) {
  return decodeHtml(text)
    .replace(/[“”]/g, '"')
    .replace(/[’]/g, "'")
    .replace(/[–—]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
}

function stripHtmlToText(html) {
  return decodeHtml(
    html
      .replace(/<style[\s\S]*?<\/style>/gi, '')
      .replace(/<script[\s\S]*?<\/script>/gi, '')
      .replace(/<hr\s*\/?>/gi, '\n* * *\n')
      .replace(/<h2[^>]*>\s*<span[^>]*>(.*?)<\/span>\s*<\/h2>/gi, '\n## $1\n')
      .replace(/<h3[^>]*>\s*<span[^>]*>(.*?)<\/span>\s*<\/h3>/gi, '\n### $1\n')
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/p>/gi, '\n\n')
      .replace(/<\/div>/gi, '\n')
      .replace(/<\/ul>/gi, '\n')
      .replace(/<li>/gi, '- ')
      .replace(/<\/li>/gi, '\n')
      .replace(/<[^>]+>/g, '')
      .replace(/\r\n/g, '\n')
      .replace(/\u00a0/g, ' ')
      .replace(/\[edit\]/gi, '')
      .replace(/\n{3,}/g, '\n\n')
      .trim(),
  )
}

function toRecordId(slug) {
  return `ose-monster-${slug.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')}`
}

function cleanMonsterText(text, pageName) {
  const lines = text
    .split('\n')
    .map(normalizeLine)
    .filter(Boolean)
    .filter((line) => line !== pageName)
    .filter((line) => line !== 'From OSE SRD')
    .filter((line) => !line.startsWith('Jump to:'))
    .filter((line) => !line.startsWith('Retrieved from '))
    .filter((line) => line !== 'Categories:')

  const cutIndex = lines.findIndex((line) => line === 'Tools')
  return cutIndex === -1 ? lines : lines.slice(0, cutIndex)
}

function extractHeadings(lines) {
  return lines.filter((line) => line.startsWith('## ') || line.startsWith('### '))
}

function parseIndexMonsterLinks(html) {
  const links = [...html.matchAll(/<a href="\/srd\/index\.php\/([^"?#]+)"\s+title="([^"]+)">([^<]+)<\/a>/g)]
  const records = []

  for (const [, slug, titleAttr, linkText] of links) {
    const title = normalizeLine(linkText || titleAttr)
    if (/^[A-Z]$/.test(title)) continue
    records.push({
      slug: decodeURIComponent(slug),
      name: title,
    })
  }

  const deduped = new Map()
  for (const entry of records) {
    if (!deduped.has(entry.slug)) deduped.set(entry.slug, entry)
  }
  return [...deduped.values()]
}

async function fetchMonsterRecord(entry) {
  const url =
    `${API_BASE}?action=parse&page=${encodeURIComponent(entry.slug)}` +
    '&prop=text|categories&format=json&formatversion=2'
  const data = await fetchJson(url)
  const html = data?.parse?.text
  if (typeof html !== 'string') {
    throw new Error(`No rendered HTML returned for monster page ${entry.slug}`)
  }

  const rawText = stripHtmlToText(html)
  const contentLines = cleanMonsterText(rawText, entry.name)
  const headings = extractHeadings(contentLines)
  const categories = Array.isArray(data?.parse?.categories)
    ? data.parse.categories
        .map((category) => {
          if (typeof category === 'string') return normalizeLine(category)
          if (category && typeof category === 'object' && typeof category['*'] === 'string') {
            return normalizeLine(category['*'])
          }
          return ''
        })
        .filter(Boolean)
    : []

  return {
    id: toRecordId(entry.slug),
    name: entry.name,
    slug: entry.slug,
    sourceUrl: `${PAGE_BASE}/${entry.slug}`,
    headings,
    categories,
    rawText: contentLines.join('\n'),
    contentLines,
  }
}

function toTsModule(records) {
  const lines = [
    "import type { OseRawMonsterRecord } from './oseRawMonsterTypes'",
    '',
    '// Generated by scripts/fetch-ose-monsters-raw.mjs',
    'export const OSE_RAW_MONSTERS: OseRawMonsterRecord[] = [',
  ]

  for (const record of records) {
    lines.push('  {')
    for (const [key, value] of Object.entries(record)) {
      lines.push(`    ${key}: ${JSON.stringify(value)},`)
    }
    lines.push('  },')
  }

  lines.push(']')
  lines.push('')
  return lines.join('\n')
}

async function main() {
  const [, , outputPathArg] = process.argv
  if (outputPathArg === '--help' || outputPathArg === '-h') {
    usage()
    return
  }

  const outputPath = path.resolve(outputPathArg ?? OUTPUT_DEFAULT)
  const indexUrl = `${API_BASE}?action=parse&page=${INDEX_PAGE}&prop=text&format=json&formatversion=2`
  const indexData = await fetchJson(indexUrl)
  const indexHtml = indexData?.parse?.text
  if (typeof indexHtml !== 'string') {
    throw new Error('No rendered HTML returned for Monster Descriptions index page')
  }

  const monsterLinks = parseIndexMonsterLinks(indexHtml)
  if (monsterLinks.length === 0) {
    throw new Error('No monster links found on Monster Descriptions page')
  }

  const records = []
  for (const entry of monsterLinks) {
    records.push(await fetchMonsterRecord(entry))
  }

  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, toTsModule(records))
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exitCode = 1
})
