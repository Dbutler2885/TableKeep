function encodedPath(path) {
  return path.split('/').map(encodeURIComponent).join('/')
}

function sourceUrl(path) {
  return `https://github.com/${SOURCE_REPOSITORY}/blob/${SOURCE_REVISION}/${encodedPath(path)}`
}

async function fetchSource(path) {
  const url = `https://raw.githubusercontent.com/${SOURCE_REPOSITORY}/${SOURCE_REVISION}/${encodedPath(path)}`
  const response = await fetch(url, { redirect: 'error', signal: AbortSignal.timeout(20_000) })
  if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`)
  return response.text()
}

function corpusLicense(source) {
  const start = source.indexOf(`### ${LICENSE_TITLE}\n`)
  const end = source.indexOf('\n## Creative Commons Attribution 4.0 International', start)
  if (start < 0 || end < 0 || !source.includes('All text and tables not declared as product identity are Open Game Content.')) {
    throw new Error('The source does not include the expected Open Game Content designation and license')
  }
  const text = source.slice(start + 4, end).trimEnd()
  if (!text.includes('15 COPYRIGHT NOTICE') || !text.endsWith('Old-School Essentials System Reference Document © 2019 Gavin Norman. Author Gavin Norman.')) {
    throw new Error('The source Open Game License copyright notice does not match the pinned release')
  }
  return [
    `Generated by ${GENERATED_BY}.\nSource: ${sourceUrl(LICENSE_FILE)}`,
    `DESIGNATION OF OPEN GAME CONTENT\n\n${OGC_NOTICE}`,
    text,
    'TableKeep Classic Fantasy Rules Corpus © 2026 David Butler.',
    'END OF LICENSE',
  ].join('\n\n') + '\n'
}

// The transcription puts merged headings in the first Markdown row and the
// actual column labels in the first data row. The progression table even
// places "Saving Throws" over XP. Put the headings on the correct columns.
function columnLabels(header, nextRow) {
  if (header.includes('Saving Throws') && nextRow?.[3] === 'THAC0') {
    return nextRow.map((cell, index) => {
      if (index < 4) return cell
      if (index < 9) return `Save ${cell}`
      return `Spells (level ${cell})`
    })
  }
  if (header.includes('Attack Roll to Hit AC')) {
    const firstArmorClass = nextRow?.indexOf('-3') ?? -1
    if (firstArmorClass < 0) throw new Error('Attack matrix is missing its column labels')
    return nextRow.map((cell, index) => index >= firstArmorClass ? `AC ${cell}` : cell)
  }
  if (header.includes('Hit Dice of Monster Type†')) {
    if (nextRow?.[0] !== 'Level') throw new Error('Turning table is missing its column labels')
    return nextRow.map((cell, index) => index === 0 ? cell : `HD ${cell}†`)
  }
  if (header.includes('Retainers') && nextRow?.[0] === 'CHA') {
    return ['CHA', 'NPC Reactions', 'Max Retainers', 'Retainer Loyalty']
  }
  if (header.includes('Wage per Month') && nextRow?.[0] === 'Type') {
    return nextRow.map((cell, index) => index < 3 ? cell : `${cell} Wage per Month`)
  }
  if (header.includes('Movement Rate') && nextRow?.[0] === 'Armor Worn') {
    return ['Armor Worn', 'Movement Rate (Without Treasure)', 'Movement Rate (Carrying Treasure)']
  }
  return header
}

function tableLines(lines) {
  if (lines.some(line => !line.endsWith('|'))) throw new Error(`Incomplete table row in: ${lines[0]}`)
  const rows = lines.map(line => line.slice(1, -1).split(/(?<!\\)\|/).map(cell => cell.trim()))
  const [header, divider, ...data] = rows
  if (!divider?.every(cell => /^:?-+:?$/.test(cell)) || rows.some(row => row.length !== header.length)) {
    throw new Error(`Malformed table starting with: ${lines[0]}`)
  }
  const labels = columnLabels(header, data[0])
  const body = labels === header ? data : data.slice(1)
  if (header.includes('Class and Level') && header.includes('Attack Roll to Hit AC')) {
    // The legacy SRD and the standard attack matrix both give 12 here.
    const row = body.find(row => row[0] === '13–15' && row[1] === '17–20' && row[2] === '21–25')
    if (row?.[4] !== '13' || labels[4] !== 'AC -2') {
      throw new Error('High-level attack table no longer matches the transcription being corrected')
    }
    row[4] = '12'
  }
  return [labels, divider.map(() => '---'), ...body].map(row => `| ${row.join(' | ')} |`)
}

function markdownLines(lines) {
  const body = lines.join('\n').trim().replace(/ *\u2014 */g, ' - ').trim()
  if (!body) return []
  return body.replace(/(?:^\|[^\n]*(?:\n|$))+/gm, table => {
    const formatted = tableLines(table.trimEnd().split('\n').map(line => line.trimEnd())).join('\n')
    return table.endsWith('\n') ? formatted + '\n' : formatted
  }).split('\n')
}

export function parseRulesPage(source, path, category) {
  const url = sourceUrl(path)
  const headings = []
  const lines = source.split(/\r?\n/)
  for (const [index, line] of lines.entries()) {
    const heading = /^(#{1,6})\s+(.+?)\s*$/.exec(line)
    if (heading) headings.push({ line: index, level: heading[1].length, title: heading[2] })
    // The transcription puts this table under Thieves without the SRD caption.
    if (path === ADVANCEMENT_PAGE && line.startsWith('| Class and Level | Attack Roll to Hit AC')) {
      headings.push({ line: index, level: 2, title: HIGH_LEVEL_TABLE, startsWithTable: true })
    }
    if (path === CHARACTER_CREATION_PAGE && /^\| Attack Roll \|/.test(line)) {
      headings.push({ line: index, level: 3, title: FIRST_LEVEL_TABLE, startsWithTable: true })
    }
  }
  const [root] = headings
  if (root?.level !== 1 || lines.slice(0, root.line).some(line => line.trim())) {
    throw new Error(`Missing top-level rules title in ${path}`)
  }
  // Two pages collect multiple source chapters. Keep those headings inside
  // their containing page and retain their subheadings.
  const hasMultipleChapters = headings.slice(1).some(heading => heading.level === 1)
  const sections = headings.flatMap((heading, index) => {
    if (path === WEAPON_RULES_PAGE && index !== 0 && heading.title !== 'Weapon Qualities') return []
    const level = path === WEAPON_RULES_PAGE && index !== 0 ? 2 : heading.level + Number(hasMultipleChapters && index !== 0)
    const firstBodyLine = heading.startsWithTable ? heading.line : heading.line + 1
    const body = lines.slice(firstBodyLine, headings[index + 1]?.line)
    return [{
      title: heading.title,
      level,
      sourceUrl: `${url}?plain=1#L${heading.line + 1}`,
      markdownLines: markdownLines(body),
    }]
  })
  if (path === WEAPON_RULES_PAGE && sections.length !== 2) {
    throw new Error('The expected Weapon Qualities section is missing')
  }
  if (!sections.some(section => section.markdownLines.length > 0) ||
      sections.some(section => /Old[- ]School Essentials|Necrotic Gnome|!\[|<\/?[a-z][a-z\d]*\b[^>]*>/i.test(
        [section.title, ...section.markdownLines].join('\n'),
      ))) {
    throw new Error(`Unexpected content in ${path}`)
  }
  return { title: root.title, category, sourceUrl: url, sections }
}

export async function importRules(readSource = fetchSource) {
  const license = corpusLicense(await readSource(LICENSE_FILE))
  const pages = []
  for (const { category, directory, pages: names } of SOURCES) {
    pages.push(...await Promise.all(names.map(async name => {
      const path = `${directory}/${name}.md`
      return parseRulesPage(await readSource(path), path, category)
    })))
  }
  return {
    corpus: {
      schemaVersion: 1,
      generatedBy: GENERATED_BY,
      source: {
        edition: '2019 Classic Fantasy SRD',
        revision: SOURCE_REVISION,
        revisionDate: SOURCE_DATE,
        sourceUrl: `https://github.com/${SOURCE_REPOSITORY}/tree/${SOURCE_REVISION}`,
        licenseUrl: sourceUrl(LICENSE_FILE),
        corrections: [
          {
            section: HIGH_LEVEL_TABLE,
            sourceUrl: ADVANCEMENT_CROSS_CHECK,
            note: 'Restored the table caption and corrected the roll to hit AC -2 from 13 to 12 for Fighter 13–15, Cleric/Thief 17–20, and Magic-User 21–25.',
          },
          {
            section: FIRST_LEVEL_TABLE,
            sourceUrl: CHARACTER_CREATION_CROSS_CHECK,
            note: 'Restored the table caption so the descending AC table is distinct from the adjacent optional ascending AC rule.',
          },
        ],
      },
      license: { name: 'Open Game License Version 1.0a', file: 'OGL.txt', notice: OGC_NOTICE },
      pages,
    },
    license,
  }
}

async function main() {
  const { values: { check } } = parseArgs({ options: { check: { type: 'boolean' } } })
  const { corpus, license } = await importRules()
  const outputs = { 'OGL.txt': license, 'corpus.json': JSON.stringify(corpus, null, 2) + '\n' }
  for (const [name, contents] of Object.entries(outputs)) {
    const target = new URL(name, OUTPUT_DIRECTORY)
    if (check) {
      if (await readFile(target, 'utf8') !== contents) throw new Error(`${name} differs from its generated contents`)
    } else {
      await writeFile(target, contents)
    }
  }
  const totalSections = corpus.pages.reduce((total, page) => total + page.sections.length, 0)
  console.log(`${check ? 'Verified' : 'Imported'} ${corpus.pages.length} pages and ${totalSections} sections`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => {
    console.error(error.message)
    process.exitCode = 1
  })
}
