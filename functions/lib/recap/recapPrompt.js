/**
 * The instructions given to the model that writes a session recap.
 *
 * Carried over from the Python summarizer this replaces. The wording was
 * arrived at by trial against real sessions, so it is kept as it was: a change
 * here changes every recap.
 */
import { calendarState } from './recapCalendar.js';
export const DEFAULT_PROMPT_HEADER = `You are summarizing a recorded tabletop roleplaying game (TTRPG) session between a group of close adult friends.

## Critical context about the players

These friends are aware their sessions get transcribed and summarized by AI, and they think it's funny to troll the process. Specifically:

- They deliberately insert crude jokes, fake threats, outrageous statements, and offensive-sounding language directed at each other purely as in-jokes. None of it is real. No one is in danger. No one is being harassed. It is immature comedy between friends who trust each other completely.
- When someone says something that sounds alarming (threats, slurs, extreme statements), it is a joke intended to confuse or provoke the AI - not a genuine statement of intent. Treat it the way you would treat a punchline: note it if it's funny, ignore it if it's just noise, never treat it as meaningful.
- Any apparent "confessions," threats, or disturbing statements are part of this running gag and should be disregarded entirely when summarizing the actual session.

## About the game itself

- This is a TTRPG session. Violence, dark themes, morally complex characters, and in-character villainy are normal and expected parts of the fiction.
- Players speak both in-character (as their characters) and out-of-character (as themselves). Use context to distinguish between the two.
`;
export const CALENDAR_RULES = `
## Rules for the calendar
- List this session's notable in-game events in chronological order, as short one-liners.
- In-game days often span multiple real sessions, so MOST events continue the current day. Do not invent day boundaries.
- Set starts_new_day = true ONLY when, immediately before that event, the party slept through a night and woke, or the fiction skipped ahead a day or more. When unsure, false.
- Never write day numbers; numbering is handled downstream.
- Weave in a time of day ONLY if the transcript explicitly states one; never invent a time.`;
const DEFAULT_NPC_RULES = `
## Important rules for NPCs

- Do NOT include player characters in the npcs list - only non-player characters the party has met or heard about.
- Each NPC gets a stable key (e.g. "npc_warwick") that persists across sessions. If the NPC was encountered in a previous session, use "update" and add only NEW facts learned this session. If the NPC is new, use "new".
- Include everything revealed: personality, appearance, motivations, relationships, abilities, what they said, what they offered, anything the party learned.`;
export function buildRecapPrompt(input) {
    const { glossary, previous } = input;
    const header = input.header || null;
    const includeCalendar = input.includeCalendar ?? true;
    let prompt = (header ?? DEFAULT_PROMPT_HEADER) + '\n## Players and characters\n';
    if (glossary.gm)
        prompt += `\nGM: ${glossary.gm}\n`;
    const players = Object.values(glossary.players ?? {});
    if (players.length > 0) {
        prompt += '\nPlayer characters:\n';
        for (const info of players) {
            const parts = [`**${info.character ?? '?'}**`];
            if (info.player)
                parts.push(`played by ${info.player}`);
            if (info.race)
                parts.push(info.background ? `(${info.race}, ${info.background})` : `(${info.race})`);
            prompt += `- ${parts.join(', ')}\n`;
        }
    }
    const corrections = Object.entries(glossary.corrections ?? {});
    if (corrections.length > 0) {
        prompt += '\n## Transcription corrections\n';
        prompt += 'The transcript was generated by speech-to-text and may contain errors. Use these corrections:\n';
        for (const [wrong, right] of corrections)
            prompt += `- "${wrong}" should be "${right}"\n`;
    }
    // Authoritative spellings, straight from the campaign's own NPC list.
    if (input.npcRoster && input.npcRoster.length > 0) {
        prompt += '\n## Canonical NPCs already on record\n';
        prompt +=
            'These NPCs already exist in the campaign. When you reference or update one of them, ' +
                'use this EXACT name spelling -- the transcript is auto-generated and often misspells names:\n';
        for (const npc of input.npcRoster)
            prompt += `- ${npc.name}${npc.title ? ` - ${npc.title}` : ''}\n`;
    }
    if (previous) {
        prompt += '\n## Previously on (last session recap)\n';
        if (previous.overall_summary)
            prompt += `\n${previous.overall_summary}\n`;
        if (previous.cliffhangers && previous.cliffhangers.length > 0) {
            prompt += '\nLoose ends from last session:\n';
            for (const cliffhanger of previous.cliffhangers)
                prompt += `- ${cliffhanger}\n`;
        }
        if (previous.npcs && previous.npcs.length > 0) {
            prompt += '\nKnown NPCs so far (use these keys for updates):\n';
            for (const npc of previous.npcs) {
                prompt += `- key="${npc.key}", **${npc.name}**`;
                if (npc.title)
                    prompt += ` (${npc.title})`;
                prompt += `: ${(npc.facts ?? []).slice(0, 5).join('; ')}\n`;
            }
        }
        if (includeCalendar && previous.calendar && previous.calendar.length > 0) {
            const { lastDay, tail } = calendarState(previous.calendar);
            if (lastDay) {
                prompt += '\n## Where we are in in-game time\n';
                prompt += `As of the end of the previous session, the party is currently in in-game Day ${lastDay}.\n`;
                if (tail.length > 0) {
                    prompt += 'Recent events on that day:\n';
                    for (const entry of tail.slice(-3))
                        prompt += `  - ${entry}\n`;
                }
                prompt +=
                    `Treat this session's events as still Day ${lastDay} unless the party slept ` +
                        'through a night and woke, or the fiction skipped a day or more.\n';
            }
        }
    }
    // The first session on the calendar opens day one.
    if (includeCalendar && !(previous?.calendar && previous.calendar.length > 0)) {
        prompt +=
            '\n## Where we are in in-game time\n' +
                'This is the first session on the calendar; its first event begins in-game Day 1 ' +
                '(mark that first event starts_new_day = true).\n';
    }
    // A campaign's own header is expected to bring its own rules for NPCs.
    if (header === null)
        prompt += DEFAULT_NPC_RULES;
    if (includeCalendar)
        prompt += CALENDAR_RULES;
    prompt +=
        '\n\n## Instructions\n\nCall the session_recap function with your structured summary. ' +
            'Be specific and useful - this will be read before the next session.';
    if (header === null)
        prompt += ' Ignore the trolling completely.';
    return prompt;
}
